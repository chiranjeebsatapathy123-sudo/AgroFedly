import os
import polib

def create_translations(lang_code, translations):
    # Ensure directory exists
    po_dir = os.path.join("locale", lang_code, "LC_MESSAGES")
    os.makedirs(po_dir, exist_ok=True)
    
    # Create PO file
    po = polib.POFile()
    po.metadata = {
        "Project-Id-Version": "1.0",
        "Report-Msgid-Bugs-To": "you@example.com",
        "POT-Creation-Date": "2023-01-01 00:00+0000",
        "PO-Revision-Date": "2023-01-01 00:00+0000",
        "Last-Translator": "you <you@example.com>",
        "Language-Team": "English <yourteam@example.com>",
        "MIME-Version": "1.0",
        "Content-Type": "text/plain; charset=utf-8",
        "Content-Transfer-Encoding": "8bit",
    }
    
    for msgid, msgstr in translations.items():
        entry = polib.POEntry(
            msgid=msgid,
            msgstr=msgstr,
        )
        po.append(entry)
        
    po.save(os.path.join(po_dir, "django.po"))
    po.save_as_mofile(os.path.join(po_dir, "django.mo"))

